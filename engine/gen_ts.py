"""Generate the app's TypeScript interface to the engine, from Anki's build output.

    python engine/gen_ts.py

Writes web/src/engine/generated/:
- anki/*_pb.ts      protobuf classes (protoc + protoc-gen-es, as Anki's own build)
- backend.ts        Anki's typed method wrappers, calling ../post instead of HTTP
- methods.ts        method name -> (service, method) numbers, for the worker

Run after engine/build.sh (which writes out/ via the build scripts).
"""

import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ANKI = ROOT / "engine" / "anki"
OUT = ROOT / "web" / "src" / "engine" / "generated"
PROTOC = ANKI / "out" / "extracted" / "protoc" / "bin" / ("protoc.exe" if os.name == "nt" else "protoc")
PLUGIN = ROOT / "web" / "node_modules" / ".bin" / ("protoc-gen-es.cmd" if os.name == "nt" else "protoc-gen-es")


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    protos = sorted(p.relative_to(ANKI / "proto").as_posix() for p in (ANKI / "proto" / "anki").glob("*.proto"))
    subprocess.run(
        [
            str(PROTOC),
            f"--plugin=protoc-gen-es={PLUGIN}",
            f"--es_out={OUT}",
            "--es_opt=target=ts",
            "-I.",
            *protos,
        ],
        check=True,
        cwd=ANKI / "proto",
    )

    backend = (ANKI / "out" / "ts" / "lib" / "generated" / "backend.ts").read_text(encoding="utf8")
    backend = backend.replace('from "./post"', 'from "../post"')
    (OUT / "backend.ts").write_text(backend, encoding="utf8", newline="\n")

    generated_py = (ANKI / "out" / "pylib" / "anki" / "_backend_generated.py").read_text(encoding="utf8")
    methods = re.findall(
        r"def (\w+)_raw\(self, message: bytes\) -> bytes:\n(?:\s+\"\"\"[\s\S]*?\"\"\"\n)?\s+return self\._run_command\((\d+), (\d+), message\)",
        generated_py,
    )
    if len(methods) < 200:
        sys.exit(f"only found {len(methods)} methods")
    lines = [
        "// Generated by engine/gen_ts.py from Anki's build output. Do not edit.",
        "",
        "/** Backend method name -> [service, method], as the engine numbers them. */",
        "export const METHODS: Record<string, readonly [number, number]> = {",
    ]
    for name, service, method in methods:
        lines.append(f"  {camel(name)}: [{service}, {method}],")
    lines.append("}")
    (OUT / "methods.ts").write_text("\n".join(lines) + "\n", encoding="utf8", newline="\n")
    print(f"{len(protos)} protos, {len(methods)} methods -> {OUT}")


if __name__ == "__main__":
    main()
